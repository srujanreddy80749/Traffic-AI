"""
Traffic Prediction Service
============================
Trains two scikit-learn models on synthetic traffic data:
  1. RandomForestClassifier  -> Predicts traffic level (Low / Medium / High)
  2. RandomForestRegressor   -> Predicts travel time in minutes

Data: Synthetic dataset generated by data/generate_data.py
      NOT real-world data.
Evaluation metrics:
  - Classification: Accuracy, F1-score (weighted)
  - Regression:     MAE, RMSE, R²
"""

import os, json, pickle
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.model_selection import train_test_split
from sklearn.metrics import (accuracy_score, f1_score,
                              mean_absolute_error, mean_squared_error, r2_score)
from sklearn.preprocessing import StandardScaler

BASE_DIR   = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_PATH  = os.path.join(BASE_DIR, 'data', 'traffic_data.csv')
MODEL_DIR  = os.path.join(BASE_DIR, 'models')
METRICS_PATH = os.path.join(MODEL_DIR, 'metrics.json')

FEATURES = ['hour', 'day_of_week', 'vehicle_count', 'weather',
            'accident', 'road_capacity', 'congestion_ratio']

LABEL_MAP = {0: 'Low', 1: 'Medium', 2: 'High'}
COLOR_MAP  = {'Low': '#2ecc71', 'Medium': '#f39c12', 'High': '#e74c3c'}


# ─────────────────────────── Training ────────────────────────────────────────

def train_models():
    """Train and persist models. Called once at app start if models are absent."""
    os.makedirs(MODEL_DIR, exist_ok=True)

    # Generate data if not present
    if not os.path.exists(DATA_PATH):
        from data.generate_data import generate_traffic_data
        os.makedirs(os.path.join(BASE_DIR, 'data'), exist_ok=True)
        df = generate_traffic_data(5000)
        df.to_csv(DATA_PATH, index=False)
    else:
        df = pd.read_csv(DATA_PATH)

    X = df[FEATURES]
    y_class = df['traffic_level']
    y_reg   = df['travel_time_min']

    X_tr, X_te, yc_tr, yc_te, yr_tr, yr_te = train_test_split(
        X, y_class, y_reg, test_size=0.2, random_state=42, stratify=y_class
    )

    # --- Classifier ---
    clf = RandomForestClassifier(n_estimators=150, max_depth=12, random_state=42)
    clf.fit(X_tr, yc_tr)
    yc_pred = clf.predict(X_te)
    clf_metrics = {
        'accuracy': round(accuracy_score(yc_te, yc_pred), 4),
        'f1_weighted': round(f1_score(yc_te, yc_pred, average='weighted'), 4),
        'classes': ['Low', 'Medium', 'High']
    }

    # --- Regressor ---
    reg = RandomForestRegressor(n_estimators=150, max_depth=12, random_state=42)
    reg.fit(X_tr, yr_tr)
    yr_pred = reg.predict(X_te)
    reg_metrics = {
        'mae':  round(mean_absolute_error(yr_te, yr_pred), 3),
        'rmse': round(float(np.sqrt(mean_squared_error(yr_te, yr_pred))), 3),
        'r2':   round(r2_score(yr_te, yr_pred), 4)
    }

    # Feature importances
    feat_imp = dict(zip(FEATURES, np.round(clf.feature_importances_, 4).tolist()))

    metrics = {
        'classification': clf_metrics,
        'regression':     reg_metrics,
        'feature_importance': feat_imp,
        'training_samples': int(len(X_tr)),
        'test_samples':     int(len(X_te)),
        'data_source': 'Synthetic (generated by data/generate_data.py)',
        'note': 'These are NOT real-world traffic measurements.'
    }

    # Persist
    with open(os.path.join(MODEL_DIR, 'classifier.pkl'), 'wb') as f:
        pickle.dump(clf, f)
    with open(os.path.join(MODEL_DIR, 'regressor.pkl'), 'wb') as f:
        pickle.dump(reg, f)
    with open(METRICS_PATH, 'w') as f:
        json.dump(metrics, f, indent=2)

    print("[Prediction] Models trained successfully.")
    print(f"  Classifier  - Accuracy: {clf_metrics['accuracy']}, F1: {clf_metrics['f1_weighted']}")
    print(f"  Regressor   - MAE: {reg_metrics['mae']} min, R²: {reg_metrics['r2']}")
    return clf, reg, metrics


# ─────────────────────────── Loading ─────────────────────────────────────────

_clf, _reg, _metrics = None, None, None

def _load_models():
    global _clf, _reg, _metrics
    clf_path = os.path.join(MODEL_DIR, 'classifier.pkl')
    reg_path = os.path.join(MODEL_DIR, 'regressor.pkl')
    if not (os.path.exists(clf_path) and os.path.exists(reg_path)):
        _clf, _reg, _metrics = train_models()
    else:
        with open(clf_path, 'rb') as f:
            _clf = pickle.load(f)
        with open(reg_path, 'rb') as f:
            _reg = pickle.load(f)
        with open(METRICS_PATH) as f:
            _metrics = json.load(f)


def get_models():
    if _clf is None:
        _load_models()
    return _clf, _reg, _metrics


# ─────────────────────────── Prediction API ──────────────────────────────────

def predict_traffic(hour: int, day_of_week: int, vehicle_count: int,
                    weather: int, accident: int, road_capacity: int):
    """
    Predict traffic level and travel time for given conditions.

    Parameters
    ----------
    hour          : 0-23
    day_of_week   : 0=Mon … 6=Sun
    vehicle_count : int
    weather       : 0=Clear, 1=Rain, 2=Fog, 3=Snow
    accident      : 0 or 1
    road_capacity : int

    Returns
    -------
    dict with keys: traffic_level (str), traffic_color, travel_time_min (float),
                    congestion_ratio (float), confidence (float), horizon_forecasts
    """
    clf, reg, _ = get_models()

    congestion_ratio = min(vehicle_count / max(road_capacity, 1), 2.0)
    row = pd.DataFrame([[hour, day_of_week, vehicle_count, weather,
                          accident, road_capacity, congestion_ratio]], columns=FEATURES)

    level_idx   = int(clf.predict(row)[0])
    proba       = clf.predict_proba(row)[0]
    confidence  = float(max(proba))
    travel_time = float(reg.predict(row)[0])

    # Horizon forecasts (15, 30, 60 min ahead) – simulate trend
    horizons = []
    for delta_min in [15, 30, 60]:
        future_hour = (hour + delta_min // 60) % 24
        # Simple demand model: peak hours shift vehicle count
        peak = 1.0
        if 7 <= future_hour <= 9 and day_of_week < 5:
            peak = 1.4
        elif 17 <= future_hour <= 20 and day_of_week < 5:
            peak = 1.5
        elif future_hour >= 23 or future_hour <= 5:
            peak = 0.5
        future_veh  = min(int(vehicle_count * peak), road_capacity)
        future_cong = min(future_veh / max(road_capacity, 1), 2.0)
        future_row  = pd.DataFrame([[future_hour, day_of_week, future_veh,
                                     weather, accident, road_capacity, future_cong]], columns=FEATURES)
        f_level = int(clf.predict(future_row)[0])
        f_time  = float(reg.predict(future_row)[0])
        horizons.append({
            'minutes_ahead': delta_min,
            'traffic_level': LABEL_MAP[f_level],
            'travel_time_min': round(f_time, 1),
            'congestion_ratio': round(future_cong, 3)
        })

    return {
        'traffic_level':    LABEL_MAP[level_idx],
        'traffic_color':    COLOR_MAP[LABEL_MAP[level_idx]],
        'traffic_index':    level_idx,
        'travel_time_min':  round(travel_time, 1),
        'congestion_ratio': round(congestion_ratio, 3),
        'confidence':       round(confidence, 3),
        'horizon_forecasts': horizons,
        'input_echo': {
            'hour': hour, 'day_of_week': day_of_week,
            'vehicle_count': vehicle_count, 'weather': weather,
            'accident': accident, 'road_capacity': road_capacity
        },
        'data_note': 'Prediction based on synthetic training data. NOT real-world traffic.'
    }


def get_metrics():
    _, _, m = get_models()
    return m
